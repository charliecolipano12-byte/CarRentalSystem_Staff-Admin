private int failedAttempts = 0;

private void attemptLogin() {
    String username = usernameTextField.getText().trim();
    char[] pw = passwordField.getPassword();
    try {
        if (username.isEmpty() || pw.length == 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Please enter your username and password.",
                    "Missing details", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        Staff staff = new StaffDAO().authenticate(username, pw);
        if (staff == null) {
            failedAttempts++;
            passwordField.setText("");
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Incorrect username or password.",
                    "Login failed", javax.swing.JOptionPane.ERROR_MESSAGE);
            if (failedAttempts >= 5) {            // pause after 5 wrong tries
                loginButton.setEnabled(false);
                javax.swing.Timer t = new javax.swing.Timer(15000, e -> {
                    failedAttempts = 0;
                    loginButton.setEnabled(true);
                });
                t.setRepeats(false);
                t.start();
            }
            return;
        }
        StaffDashboard dash = new StaffDashboard(staff);
        dash.pack();
        dash.setLocationRelativeTo(null);
        dash.setVisible(true);
        this.dispose();
    } catch (java.sql.SQLException ex) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Cannot reach the database:\n" + ex.getMessage(),
                "Database error", javax.swing.JOptionPane.ERROR_MESSAGE);
    } finally {
        java.util.Arrays.fill(pw, '\0');          // wipe the password from memory
    }
}
