   public void setBooking(Booking booking) {
    this.booking = booking;
    Customer c = booking.getCustomer();

    csName.setText(nz(c.getFullName()));
    csEmail.setText(nz(c.getEmail()));
    csPhoneNumber2.setText(nz(c.getPhone()));
    csLicenseNo.setText(nz(c.getLicenseNo()));
    csAddress.setText("-");      // not stored in the database yet
    

    if (c.isVip()) {
        lblVip.setText("★ VIP (" + c.getCompletedRentals() + " rentals)");
        lblVip.setForeground(new Color(212, 175, 55));
    } else {
        lblVip.setText(c.rentalsToVip() + " more rentals to VIP");
        lblVip.setForeground(Color.GRAY);
    }

    csBookingId.setText(booking.getId());
    csStatus.setText(booking.getStatus());
    csDateTime.setText(booking.getTimestamp().format(FMT));
    csWaiting.setText(java.time.Duration.between(
            booking.getTimestamp(), java.time.LocalDateTime.now()).toMinutes() + " min");
    carPickupDate.setText(booking.getPickup().format(FMT));
    carReturnDate.setText(booking.getReturnDate().format(FMT));
    long days = Math.max(1, (long) Math.ceil(java.time.temporal.ChronoUnit.HOURS
            .between(booking.getPickup(), booking.getReturnDate()) / 24.0));
    rentalDuration.setText(days + (days == 1 ? " day" : " days"));
    rentalTotalBill.setText(String.format("PHP %,.2f", booking.getTotal()));

    try {
        Car car = new CarDAO().findById(booking.getCarId());
        if (car != null) {
            rentalCarModel.setText(car.getModel());
            rentalCarType.setText(car.getType());
            rentalPlateNumber.setText(car.getPlate());
            rentalCarRate.setText(String.format("PHP %,.0f", car.getDailyRate()));
            rentalDailyRate.setText(String.format("PHP %,.2f / day", car.getDailyRate()));
        }
    } catch (java.sql.SQLException ex) {
        logger.log(java.util.logging.Level.WARNING, "Could not load car details", ex);
    }
}

