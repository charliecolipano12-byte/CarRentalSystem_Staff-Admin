    private void btnConfirmBookingActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmBookingActionPerformed
      if (booking == null) return;
    int choice = JOptionPane.showConfirmDialog(this,
            "Confirm booking " + booking.getId() + "?", "Confirm Booking",
            JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE);
    if (choice != JOptionPane.YES_OPTION) return;
    try {
        String problem = new BookingDAO().confirm(booking.getDbId(), staffId());
        if (problem != null) {
            JOptionPane.showMessageDialog(this, problem, "Cannot confirm",
                    JOptionPane.WARNING_MESSAGE);
            if (BookingDAO.ALREADY_PROCESSED.equals(problem)) dispose();  // dashboard resyncs
            return;
        }
        processed = true;
        JOptionPane.showMessageDialog(this, "Booking " + booking.getId() + " confirmed.",
                "Done", JOptionPane.INFORMATION_MESSAGE);
        dispose();
    } catch (java.sql.SQLException ex) {
        JOptionPane.showMessageDialog(this,
                "Could not save to the database:\n" + ex.getMessage()
                + "\nThe booking is still in the queue.",
                "Database error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnConfirmBookingActionPerformed

    private void btnRejectBookingActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRejectBookingActionPerformed
        if (booking == null) return;
    String reason = JOptionPane.showInputDialog(this,
            "Reason for rejecting this booking:", "Reject Booking",
            JOptionPane.QUESTION_MESSAGE);
    if (reason == null) return;
    reason = reason.trim();
    if (reason.isEmpty() || reason.length() > 255) {
        JOptionPane.showMessageDialog(this,
                "Please enter a reason (up to 255 characters).",
                "Invalid reason", JOptionPane.WARNING_MESSAGE);
        return;
    }
    try {
        boolean ok = new BookingDAO().changeStatus(booking.getDbId(),
                Booking.PENDING, Booking.REJECTED, staffId(), reason);
        if (!ok) {
            JOptionPane.showMessageDialog(this, BookingDAO.ALREADY_PROCESSED,
                    "Cannot reject", JOptionPane.WARNING_MESSAGE);
            dispose();                       // dashboard resyncs
            return;
        }
        processed = true;
        JOptionPane.showMessageDialog(this, "Booking " + booking.getId() + " rejected.",
                "Done", JOptionPane.INFORMATION_MESSAGE);
        dispose();
    } catch (java.sql.SQLException ex) {
        JOptionPane.showMessageDialog(this,
                "Could not save to the database:\n" + ex.getMessage()
                + "\nThe booking is still in the queue.",
                "Database error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnRejectBookingActionPerformed

